/**
 * 与目标实例版本比对。
 * 只能比较「版本号」——要拿到目标实例真实的码集，必须抓它的前端 chunk（见 steps）。
 */
export function compareRuleset({ targetVersion }) {
  const versionMatch = targetVersion === CALIBRATED_WITH;
  return {
    calibratedWith: CALIBRATED_WITH,
    targetVersion: targetVersion || 'unknown',
    versionMatch,
    officialCodeCount: DIAGNOSTIC_CODES.length,
    localIssueCount: Object.keys(LOCAL_ISSUE_TO_DIAGNOSTIC).length,
    coverageRatio: (Object.keys(LOCAL_ISSUE_TO_DIAGNOSTIC).length / DIAGNOSTIC_CODES.length).toFixed(3),
    unmappedOfficialCodes: DIAGNOSTIC_CODES.filter(c => !Object.values(LOCAL_ISSUE_TO_DIAGNOSTIC).includes(c)).length,
    verdict: versionMatch ? 'aligned' : 'version_drift',
    hint: versionMatch
      ? '目标实例版本与内置规则集校准版本一致，本地判定可直接参考'
      : `目标实例是 ${targetVersion || '未知版本'}，内置规则集按 ${CALIBRATED_WITH} 校准 —— 可能出现「平台新增规则我不知道」的情况，建议重新校准`
  };
}

/** 重新校准的操作步骤（给人/agent 看，不自动执行） */
export function calibrateRuleset() {
  return {
    steps: [
      '1. 打开目标实例任意工作流的编辑器页面（触发前端 chunk 加载）',
      '2. 用 CDP 抓 performance.getEntriesByType("resource") 里所有 .js URL',
      '3. 下载这些 chunk，grep -oh "\"WORKFLOW_[A-Z_]*\"" 得到该实例的诊断码全集',
      '4. 对比本文件的 DIAGNOSTIC_CODES，新增的补进来，并更新 CALIBRATED_WITH',
      '5. 检查新增诊断码是否对应新的校验规则，补进 lib/validate.mjs'
    ],
    why: '校验规则是平台行为的一部分，平台升级会漂；本地规则表必须有版本锚点，否则会静默过期'
  };
}
